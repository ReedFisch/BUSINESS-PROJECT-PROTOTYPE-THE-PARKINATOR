function makeDraggable(elmnt) {
    let pos1 = 0, pos2 = 0, pos3 = 0, pos4 = 0;
    elmnt.onmousedown = dragMouseDown;

    function dragMouseDown(e) {
        e = e || window.event;
        e.preventDefault(); // Always prevent default first

        if (!window.isEditingLocation) return; // Lock if not editing

        pos3 = e.clientX;
        pos4 = e.clientY;
        document.onmouseup = closeDragElement;
        document.onmousemove = elementDrag;
        elmnt.style.cursor = "grabbing";
    }

    function elementDrag(e) {
        e = e || window.event;
        e.preventDefault();
        pos1 = pos3 - e.clientX;
        pos2 = pos4 - e.clientY;
        pos3 = e.clientX;
        pos4 = e.clientY;

        let newTop = elmnt.offsetTop - pos2;
        let newLeft = elmnt.offsetLeft - pos1;

        const parent = elmnt.parentElement;
        const maxW = parent.clientWidth;
        const maxH = parent.clientHeight;

        if (newTop < 0) newTop = 0;
        if (newLeft < 0) newLeft = 0;
        if (newTop > maxH) newTop = maxH;
        if (newLeft > maxW) newLeft = maxW;

        elmnt.style.top = newTop + "px";
        elmnt.style.left = newLeft + "px";
    }

    function closeDragElement() {
        document.onmouseup = null;
        document.onmousemove = null;
        elmnt.style.cursor = window.isEditingLocation ? "grab" : "default";
    }
}

function getStartLocation() {
    const pin = document.getElementById('start-pin');
    const map = document.getElementById('fake-map');

    if (pin && map) {
        const rect = pin.getBoundingClientRect();
        const mapRect = map.getBoundingClientRect();
        const cx = rect.left + (rect.width / 2) - mapRect.left;
        const cy = rect.bottom - mapRect.top;
        return {
            x: (cx / mapRect.width) * 100,
            y: (cy / mapRect.height) * 100
        };
    }
    return { x: 95, y: 50 };
}
const FEEDER_X = 89.94; // Precise Feeder Road X
const ROAD_Y_LEVELS = [2.03, 24.70, 51.78, 83.25]; // Precise Aisle Ys

function getNearestRoadY(y) {
    // Find the closest road Y level to the given Y coordinate
    return ROAD_Y_LEVELS.reduce((prev, curr) =>
        Math.abs(curr - y) < Math.abs(prev - y) ? curr : prev
    );
}

function getAccessY(spot) {
    // Map spots to their specific driving aisle based on layout
    // Row A (Top, ~7%) -> Top Road (2.03%)
    // Row B (~15%) & C (~34%) -> Middle Road 1 (24.7%)
    // Row D (~42%) & E (~62%) -> Middle Road 2 (51.78%)
    // Bottom Area -> Bottom Road (83.25%)

    const y = spot.top;
    if (y < 12) return 2.03;      // Row A
    if (y < 38) return 24.70;     // Row B/C
    if (y < 70) return 51.78;     // Row D/E
    return 83.25;                 // Bottom / Other
}

function drawPath(targetSpot) {
    const svg = document.getElementById('path-overlay');
    if (!svg) return;

    svg.innerHTML = '';
    if (!targetSpot) return;

    const start = getStartLocation();

    // Natural Road Logic:
    // 1. Pull out to nearest Aisle (Vertical)
    // 2. Drive to Feeder (Horizontal)
    // 3. Drive along Feeder (Vertical)
    // 4. Turn into Target Aisle (Horizontal)
    // 5. Pull into Spot (Vertical)

    const startRoadY = getNearestRoadY(start.y);
    const targetRoadY = getAccessY(targetSpot);

    const p1 = `${start.x},${start.y}`;           // Start
    const p2 = `${start.x},${startRoadY}`;        // Pull out
    const p3 = `${FEEDER_X},${startRoadY}`;       // Drive to Feeder
    const p4 = `${FEEDER_X},${targetRoadY}`;      // Drive along Feeder
    const p5 = `${targetSpot.left},${targetRoadY}`; // Drive to Spot X
    const p6 = `${targetSpot.left},${targetSpot.top}`; // Pull in

    const poly = document.createElementNS("http://www.w3.org/2000/svg", "polyline");
    // Simplify path if start/target share a road or other optimizations could happen, 
    // but full 6-point path is safest "natural" default.
    poly.setAttribute("points", `${p1} ${p2} ${p3} ${p4} ${p5} ${p6}`);

    poly.setAttribute("fill", "none");
    poly.setAttribute("stroke", "#2196F3"); // Blue path
    poly.setAttribute("stroke-width", "3");
    poly.setAttribute("stroke-dasharray", "4,4"); // Tighter dash
    poly.setAttribute("stroke-linejoin", "round");
    poly.setAttribute("stroke-linecap", "round");

    // Animate
    const anim = document.createElementNS("http://www.w3.org/2000/svg", "animate");
    anim.setAttribute("attributeName", "stroke-dashoffset");
    anim.setAttribute("from", "100");
    anim.setAttribute("to", "0");
    anim.setAttribute("dur", "2.5s");
    anim.setAttribute("repeatCount", "indefinite");

    poly.appendChild(anim);
    svg.appendChild(poly);
}

function calculateRoadDistance(start, spot) {
    const startRoadY = getNearestRoadY(start.y);
    const targetRoadY = getAccessY(spot);

    // Dist = PullOut + DriveToFeeder + FeederTravel + DriveToSpotX + PullIn
    return Math.abs(start.y - startRoadY) +
        Math.abs(start.x - FEEDER_X) +
        Math.abs(startRoadY - targetRoadY) +
        Math.abs(FEEDER_X - spot.left) +
        Math.abs(targetRoadY - spot.top);
}

window.findCheapest = () => {
    let best = null;
    let minDist = Infinity;
    const start = getStartLocation();

    allSpots.forEach(s => {
        if (s.type === 'disability') return;
        if (s.status === 'free' && !myReservations.some(r => r.id === s.id)) {
            const dist = calculateRoadDistance(start, s);

            if (!best) {
                best = s;
                minDist = dist;
            } else {
                if (s.price < best.price) {
                    best = s;
                    minDist = dist;
                } else if (s.price === best.price && dist < minDist) {
                    best = s;
                    minDist = dist;
                }
            }
        }
    });

    if (best) {
        highlight(best.id);
        drawPath(best);
        alert(`💲 Cheapest: ${best.id}\n$${best.price.toFixed(2)}/hr\n(Following road rules)`);
    }
    else alert("No regular spots available!");
};

